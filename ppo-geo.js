/* ------------------------------------------------------------- API поиска */
function regions(){ return DATA.map(function(x){ return x.reg; }); }

function regRec(reg){
  var s = String(reg||'').trim().toLowerCase();
  for (var i=0;i<DATA.length;i++) if (DATA[i].reg.toLowerCase() === s) return DATA[i];
  return null;
}
function districts(reg){
  var r = regRec(reg);
  return r ? r.list.map(function(x){ return x.d; }) : [];
}
function distRec(reg, dist){
  var r = regRec(reg); if (!r) return null;
  var s = String(dist||'').trim().toLowerCase();
  for (var i=0;i<r.list.length;i++) if (r.list[i].d.toLowerCase() === s) return r.list[i];
  return null;
}
function points(reg, dist){
  var x = distRec(reg, dist);
  return x ? x.p.slice() : [];
}

/* Климат по району. Возвращает null, если район не найден: вызывающая сторона
   не должна подставлять «значения по умолчанию» — пустое поле честнее. */
function climate(reg, dist){
  var x = distRec(reg, dist);
  if (!x) return null;
  return {
    wind: x.w, w0: WIND[x.w] || '',
    ice:  x.g, b:  ICE[x.g]  || '',
    seis: x.s || '',
    ter:  TER[x.t] || '',
    reg:  reg, dist: x.d
  };
}

/* Поиск населённого пункта по всем районам. Возвращает список совпадений:
   одноимённые станицы встречаются в разных районах, выбирать должен человек. */
function findPoint(name){
  var q = String(name||'').trim().toLowerCase();
  if (q.length < 2) return [];
  var out = [];
  DATA.forEach(function(R){
    R.list.forEach(function(x){
      x.p.forEach(function(p){
        var lp = p.toLowerCase();
        if (lp === q || lp.indexOf(q) === 0)
          out.push({ reg:R.reg, dist:x.d, point:p, exact:(lp === q) });
      });
    });
  });
  out.sort(function(a,b){ return (b.exact?1:0) - (a.exact?1:0); });
  return out.slice(0, 40);
}

/* Разбор старого свободного текста «Место расположения» при переходе на
   структурированный ввод: пытаемся узнать район, затем населённый пункт.
   Ничего не угадываем силой — что не распозналось, остаётся текстом. */
function parsePlace(text){
  var s = String(text||'').trim();
  if (!s) return null;
  var low = s.toLowerCase();
  /* Название региона убираем из строки до поиска района: иначе «Краснодарский
     край» перебивает «Динской район» — по подстроке «краснодар». */
  DATA.forEach(function(R){ low = low.split(R.reg.toLowerCase()).join(' '); });
  var hitDist = null, hitReg = null, hitLen = 0;
  DATA.forEach(function(R){
    R.list.forEach(function(x){
      var base = x.d.toLowerCase().replace(/^городской округ\s+/, '').replace(/\s+район$/, '');
      if (base.length > 3 && low.indexOf(base) >= 0 && base.length > hitLen){
        hitDist = x.d; hitReg = R.reg; hitLen = base.length;
      }
    });
  });
  var hitPoint = '';
  if (hitDist){
    var pl = points(hitReg, hitDist);
    pl.forEach(function(p){
      if (!hitPoint && low.indexOf(p.toLowerCase()) >= 0) hitPoint = p;
    });
  } else {
    /* района в строке нет — пробуем опознать по населённому пункту */
    var words = s.split(/[,;]/).map(function(w){
      return w.replace(/^\s*(г\.|город|ст-?ца|станица|ст\.|пос\.|посёлок|поселок|х\.|хутор|с\.|село|аул|пгт)\s*/i,'').trim();
    }).filter(Boolean);
    for (var i=0;i<words.length && !hitDist;i++){
      var f = findPoint(words[i]);
      if (f.length && f[0].exact){ hitReg = f[0].reg; hitDist = f[0].dist; hitPoint = f[0].point; }
    }
  }
  if (!hitDist) return null;
  return { reg:hitReg, dist:hitDist, point:hitPoint, rest:s };
}

/* Сборка строки «Место расположения» из частей — единый формат записи. */
function composePlace(reg, dist, point){
  var a = [];
  if (point) a.push(point);
  if (dist)  a.push(dist);
  if (reg)   a.push(reg);
  return a.join(', ');
}


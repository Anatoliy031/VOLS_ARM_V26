function actKey(a){
  return [String(a.grp || '').slice(0, 3), String(a.line || ''),
          String(a.num || ''), String(a.act || '')].join('|').toLowerCase().trim();
}
function buildActs(){
  var d = load(), out = [], done = {};
  function add(grp, line, num, act, base, perf, term, cost){
    var r = { grp:grp, line:line || '', num:num || '', act:act, base:base || '',
              performer:perf || '', term:term || '', cost:cost || '', manual:0 };
    r.key = actKey(r);
    out.push(r);
    return r;
  }

  /* Е.2 — дефекты несущих конструкций, выявленные осмотром.
     Исполнитель берётся из карточки дефекта: раньше он там назначался,
     но в отчёт не попадал — вместо него всегда стоял владелец. */
  d.poles.forEach(function(p){
    var x = poleDerived(p);
    if (!x.act) return;
    var key = 'P|' + (p.line || '') + '|' + (p.num || '');
    if (done[key]) return; done[key] = 1;
    add(LISTS.actGrp[1], p.line, p.num, x.act, x.defTxt,
        p.performer || 'Владелец инфраструктуры', p.term || '', p.cost || '');
  });
  /* Е.2 — несоответствия фактического состояния (протокол Г.1) */
  d.meas.forEach(function(m){
    if (!isBadVerdict(m.verdict)) return;
    if ((m.proto || measProto(m.kindId)) !== LISTS.proto[0]) return;
    var key = 'P|' + (m.line || '') + '|' + (m.pole || '');
    if (done[key]) return; done[key] = 1;
    add(LISTS.actGrp[1], m.line, m.pole,
        'Устранение несоответствия фактического состояния конструкции',
        (m.name || '') + ': ' + (m.value || '') + ' ' + (m.unit || '') +
        ' при норме — ' + (m.norm || ''),
        'Владелец инфраструктуры', m.deadline || '', m.cost || '');
  });
  /* Е.1 — недостаточность свободных интервалов (протокол Г.2) */
  d.meas.forEach(function(m){
    if (!isBadVerdict(m.verdict)) return;
    if ((m.proto || measProto(m.kindId)) !== LISTS.proto[1]) return;
    add(LISTS.actGrp[0], m.line, m.pole,
        'Проектное решение по размещению ОК с обеспечением нормируемого расстояния',
        (m.name || '') + ': ' + (m.value || '') + ' ' + (m.unit || '') +
        ' при норме — ' + (m.norm || ''),
        'Пользователь инфраструктуры', m.deadline || '', m.cost || '');
  });
  /* Е.1 — поверочный расчёт по опорам, для которых количественная оценка не выдана */
  var needCalc = {};
  d.poles.forEach(function(p){
    var r = poleByMark(p.mark); if (!r || !poleTensioned(r.sch)) return;
    if (d.wires.length && d.wires.every(function(w){ return parseFloat(w.tens) > 0; })) return;
    needCalc[p.mark] = (needCalc[p.mark] || 0) + 1;
  });
  Object.keys(needCalc).forEach(function(mk){
    add(LISTS.actGrp[0], '—', 'опор данной марки: ' + needCalc[mk],
        'Поверочный расчёт несущей способности опор марки ' + mk +
        ' с учётом момента от тяжения (в составе проектной документации)',
        'Тяжение проводов и ранее размещённых кабелей при обследовании не установлено (пункт 6 ТТ № 282р)',
        'Пользователь инфраструктуры');
  });
  /* Е.1 — пролёты свыше габаритного */
  d.poles.forEach(function(p){
    var x = poleDerived(p);
    if (!x.overSpan) return;
    add(LISTS.actGrp[0], p.line, p.num,
        'Поверочный расчёт пролёта, превышающего габаритный (в составе проектной документации)',
        'Фактический пролёт ' + p.span + ' м при габаритном ' + x.lgab +
        ' м для марки ' + (p.mark || ''),
        'Пользователь инфраструктуры');
  });

  /* --- наложение ручных правок --- */
  var over = {};
  (d.acts || []).forEach(function(a){ if (a && a.key && !a.manual) over[a.key] = a; });
  out = out.filter(function(r){ return !(over[r.key] && over[r.key].off); });
  out.forEach(function(r){
    var o = over[r.key]; if (!o) return;
    if (String(o.performer || '') !== '') r.performer = o.performer;
    if (String(o.term || '') !== '') r.term = o.term;
    if (String(o.cost || '') !== '') r.cost = o.cost;
    if (String(o.actText || '') !== '') r.act = o.actText;
    r.edited = 1;
  });
  /* --- позиции, добавленные вручную --- */
  (d.acts || []).forEach(function(a){
    if (!a || !a.manual || a.off) return;
    out.push({ grp:a.grp || LISTS.actGrp[1], line:a.line || '', num:a.num || '',
               act:a.actText || a.act || '', base:a.base || '',
               performer:a.performer || '', term:a.term || '', cost:a.cost || '',
               manual:1, key:a.key });
  });
  /* сначала Е.1, затем Е.2 — как в приложении Е отчёта */
  out.sort(function(a, b){
    var ga = String(a.grp).indexOf('Е.1') === 0 ? 0 : 1;
    var gb = String(b.grp).indexOf('Е.1') === 0 ? 0 : 1;
    return ga - gb;
  });
  return out;
}


/* Категория хранится латинской «A». Пользователь и внешние файлы могут прислать
   кириллическую «А» — приводим к одному виду ВСЕГДА через normCat().          */
function normCat(c){
  var t = String(c === undefined || c === null ? '' : c).trim().toUpperCase();
  if (t === '\u0410') t = 'A';           // кириллическая А → латинская A
  /* Латинская «B» внешне неотличима от кириллической «В» — приводим к «В».
     Раньше здесь стояла замена «В» → «Б»: категория В (исправное, устранение
     при плановом обслуживании) молча становилась Б с мероприятием «выправка /
     усиление», и в отчёт категория В не попадала вовсе. */
  if (t === 'B') t = '\u0412';
  if (t === '') t = '—';
  if (t === '-' || t === '\u2013') t = '—';
  return t;
}

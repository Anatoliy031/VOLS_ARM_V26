function poleDerived(p){
  var ref = poleByMark(p.mark) || {};
  var df  = defectByCat(p.defect || '—');
  return {
    mat: ref.mat || '', ptype: ref.type || '', proj: ref.proj_full || ref.proj || '',
    st: ref.st || '', sch: ref.sch || '', lgab: ref.lgab || '',
    m_adm: ref.m_adm || '', h: ref.h || '', kDef: df.k,
    approx: ref.approx ? 1 : 0,        /* несущая способность принята по стойке-аналогу */
    endPole: p.endPole ? 1 : 0,        /* конечная (концевая) опора — пролёта нет */
    /* Графа «Дефект» заполняется только при выбранной категории: без категории
       опора дефектной не считается, а её описание идёт в примечание. */
    defTxt: (normCat(p.defect) === '—') ? ''
          : ((p.defText && String(p.defText).trim()) ? String(p.defText).trim()
             : defTypicalTxt(df, ref)),
    state: df.state, tv: df.tv, act: df.act, note: df.note, grp: df.grp,
    mest: p.mest || defMest(p), angle: p.angle || '',
    overSpan: (ref.lgab && parseFloat(p.span) > ref.lgab) ? 1 : 0,
    performer: p.performer || '', term: p.term || '', cost: p.cost || ''
  };
}

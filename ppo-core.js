/* Правка объекта в другой вкладке.
   Карта и осмотр — разные страницы, и в поле их держат открытыми
   одновременно. Раньше каждая вкладка читала объект один раз при загрузке
   и держала его в переменной: опора, добавленная на карте, в осмотре не
   появлялась до перезагрузки страницы. Теперь ядро следит за хранилищем и
   сообщает страницам, что данные изменились. */
function watchExternal(){
  if (typeof window === 'undefined' || !window.addEventListener) return;
  window.addEventListener('storage', function(e){
    if (!e || e.key !== STORE_KEY) return;
    var was = _data;
    _data = null;
    try {
      document.dispatchEvent(new CustomEvent('ppo:external', {
        detail:{ hadData: !!was, poles: load().poles.length }
      }));
    } catch (err) {}
  });
  /* Событие storage не приходит, если вкладку вернули из кэша переходов
     назад/вперёд либо если правка пришла из того же окна другим путём.
     На возврате фокуса сверяем отметку записи и при расхождении обновляем. */
  var recheck = function(){
    var mark = '';
    try { mark = localStorage.getItem(STORE_KEY + '_stamp') || ''; } catch (e) {}
    if (!mark || mark === _stamp) return;
    _stamp = mark;
    _data = null;
    try {
      document.dispatchEvent(new CustomEvent('ppo:external', {
        detail:{ hadData:true, poles: load().poles.length }
      }));
    } catch (e) {}
  };
  window.addEventListener('focus', recheck);
  document.addEventListener('visibilitychange', function(){
    if (!document.hidden) recheck();
  });
}


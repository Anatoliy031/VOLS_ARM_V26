/* Копия сохраняет и снимки: они лежат не в общем хранилище, а в отдельной
   базе браузера, и без такой упаковки терялись при восстановлении. */
function blobToDataUrl(b){
  return new Promise(function(res){
    var fr = new FileReader();
    fr.onload = function(){ res(fr.result); };
    fr.onerror = function(){ res(''); };
    fr.readAsDataURL(b);
  });
}
function dataUrlToBlob(u){
  var m = /^data:([^;,]+)?(;base64)?,/.exec(String(u||''));
  if (!m) return null;
  var type = m[1] || 'image/jpeg', body = String(u).slice(m[0].length);
  var bin = m[2] ? atob(body) : decodeURIComponent(body);
  var arr = new Uint8Array(bin.length);
  for (var i = 0; i < bin.length; i++) arr[i] = bin.charCodeAt(i);
  return new Blob([arr], { type:type });
}

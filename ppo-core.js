/* Текст графы «Примечание»: сначала то, что записал осмотрщик в поле
   (например «отклонение от оси»), затем типовое последствие по категории. */
/* Служебная графа листа «Опоры»: машинные признаки, которых нет в других
   графах, — конец участка и ручная привязка соседних опор. */
function svcMark(p){
  var t = [];
  if (p.endPole) t.push('КОНЕЧНАЯ');
  if (p.prevRef) t.push('ПРЕД=' + p.prevRef);
  if (p.nextRef) t.push('СЛЕД=' + p.nextRef);
  return t.join('; ');
}
function svcParse(v){
  var t = String(v || ''), out = { endPole:0, prevRef:'', nextRef:'' };
  if (/конечн/i.test(t)) out.endPole = 1;
  var mp = t.match(/ПРЕД=([^;]*)/i); if (mp) out.prevRef = mp[1].trim();
  var mn = t.match(/СЛЕД=([^;]*)/i); if (mn) out.nextRef = mn[1].trim();
  return out;
}

/* Типовое описание дефекта по категории с поправкой на материал стойки:
   для деревянной опоры формулировка про защитный слой бетона бессмысленна. */
function defTypicalTxt(df, ref){
  if (!df) return '';
  if (df.txtWood && /дерев/i.test(String((ref && ref.mat) || ''))) return df.txtWood;
  return df.txt || '';
}

function poleNote(p){
  var df = defectByCat(p.defect || '—');
  var own = String(p.note || '').trim();
  var typ = String(df.note || '').trim();
  var out = (own && typ && own.toLowerCase().indexOf(typ.toLowerCase()) < 0) ? (own + '; ' + typ) : (own || typ);
  /* Описание, сделанное без категории дефекта, — это наблюдение исполнителя,
     а не дефект. В ведомость оно не идёт, но и теряться не должно: место ему
     в примечании к опоре. */
  if (normCat(p.defect) === '—'){
    var obs = String(p.defText || '').trim();
    if (obs && out.toLowerCase().indexOf(obs.toLowerCase()) < 0)
      out = out ? (out + '; ' + obs) : obs;
  }
  /* Признак конечной опоры должен быть виден в отчёте: иначе пустая графа
     «пролёт» читается как незаполненные данные, а не как конец участка. */
  if (p.endPole){
    var t = 'конечная (концевая) опора — пролёт до следующей опоры не определяется';
    if (out.toLowerCase().indexOf('конечная (концевая)') < 0) out = out ? (out + '; ' + t) : t;
  }
  return out;
}

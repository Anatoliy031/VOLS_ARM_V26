function A1(r, c){ return XLSX.utils.encode_cell({ r:r-1, c:c-1 }); }
function setCell(ws, r, c, v){
  var a = A1(r, c);
  if (v === '' || v === null || v === undefined){ delete ws[a]; return; }
  if (typeof v === 'number' && isFinite(v)) ws[a] = { t:'n', v:v };
  else ws[a] = { t:'s', v:String(v) };
}
function clearCell(ws, r, c){ delete ws[A1(r, c)]; }
function sheetRows(ws){
  if (!ws || !ws['!ref']) return 0;
  return XLSX.utils.decode_range(ws['!ref']).e.r + 1;
}
function expandRef(ws, rows, cols){
  var rg = ws['!ref'] ? XLSX.utils.decode_range(ws['!ref']) : { s:{r:0,c:0}, e:{r:0,c:0} };
  rg.e.r = Math.max(rg.e.r, rows-1);
  rg.e.c = Math.max(rg.e.c, cols-1);
  ws['!ref'] = XLSX.utils.encode_range(rg);
}
function sheetNamed(wb, want){
  var w = want.toLowerCase();
  var n = wb.SheetNames.filter(function(x){ return x.trim().toLowerCase() === w; })[0];
  return n ? wb.Sheets[n] : null;
}


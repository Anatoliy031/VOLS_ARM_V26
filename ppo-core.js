/* Контекст расчёта для КОНКРЕТНОЙ опоры.
   Раньше нормативы по всем опорам считались по наибольшему классу напряжения
   объекта: на смешанном участке 0,4/10 кВ опоры 0,4 кВ оценивались по 10 кВ.
   Класс берётся у самой опоры, характер местности — тоже её собственный,
   и лишь при их отсутствии подставляются общие по объекту. */
function ctxForPole(p){
  var c = ctx();
  if (!p) return c;
  var kv = String(p.kv || '').trim();
  var ms = String(p.mest || '').trim();
  return { kv: kv || c.kv, kvList: c.kvList,
           mestnost: ms || c.mestnost, object: c.object,
           poleNum: p.num || '', poleLine: p.line || '' };
}
/* поиск опоры по номеру и линии — измерения хранят их, а не идентификатор */
function poleByNum(num, line){
  var d = load(), n = String(num || '').trim(), l = String(line || '').trim();
  if (!n) return null;
  var hit = null;
  d.poles.forEach(function(p){
    if (hit) return;
    if (String(p.num).trim() !== n) return;
    if (l && String(p.line || '').trim() !== l) return;
    hit = p;
  });
  if (hit || !l) return hit;
  d.poles.forEach(function(p){ if (!hit && String(p.num).trim() === n) hit = p; });
  return hit;
}
/* контекст по номеру опоры из записи измерения */
function ctxForMeas(m){
  return ctxForPole(m ? poleByNum(m.pole, m.line) : null);
}
/* все классы напряжения, фактически встречающиеся на объекте:
   отмеченные в паспорте плюс проставленные в карточках опор */
function kvUsed(){
  var d = load(), c = ctx(), out = [], seen = {};
  c.kvList.forEach(function(k){ if (k && !seen[k]){ seen[k] = 1; out.push(k); } });
  d.poles.forEach(function(p){
    var k = String(p.kv || '').trim();
    if (k && !seen[k]){ seen[k] = 1; out.push(k); }
  });
  return out.sort(function(a, b){
    return parseFloat(String(a).replace(',', '.')) - parseFloat(String(b).replace(',', '.'));
  });
}
function maxKv(s){
  var arr = String(s||'').split(';').map(function(x){ return x.trim(); }).filter(Boolean);
  if (!arr.length) return '';
  var best = arr[0], bn = -1;
  arr.forEach(function(x){
    var n = parseFloat(x.replace(',','.'));
    if (n > bn) { bn = n; best = x; }
  });
  return best;
}


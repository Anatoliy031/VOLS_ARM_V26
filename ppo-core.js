/* приведение объекта из старых версий к текущей схеме — без потери данных */
function migrate(o){
  if (!o || typeof o !== 'object') return blank();
  var b = blank();
  ['pass','lines','poles','meas','si','cables','wires','acts','skips'].forEach(function(k){
    if (o[k] === undefined || o[k] === null) o[k] = b[k];
  });
  o.poles.forEach(function(p){
    if (p.defect !== undefined) p.defect = normCat(p.defect);
    /* Источник пролёта. Пролёты, посчитанные по координатам, пересчитываются
       при перемещении метки на карте; введённые вручную — нет. У файлов старых
       версий признака нет: там пролёт пришёл из обхода, поэтому считаем его
       расчётным, но пересчёт по умолчанию делаем только по явной команде. */
    if (p.spanSrc === undefined) p.spanSrc = '';
    if (p.mest === undefined) p.mest = '';
    if (p.angle === undefined) p.angle = '';
    if (p.prevOwner === undefined) p.prevOwner = '';
    if (p.prevH === undefined) p.prevH = '';
    /* Признак конечной (концевой) опоры. Пролёт «до следующей» у такой опоры
       не существует: цепь на ней обрывается. Признак ставится вручную и
       сильнее геометрии — на карте следующая по номеру метка может стоять
       рядом, но линия там уже закончилась. */
    if (p.endPole === undefined) p.endPole = 0;
    p.endPole = p.endPole ? 1 : 0;
    /* Ручная привязка соседних опор. Геометрический ход строится в пределах
       линии, поэтому опора, продолжение которой лежит на другой линии или в
       другом классе напряжения, оставалась без пролёта. Здесь исполнитель
       указывает соседа явно — пролёт всё равно считается по координатам,
       вручную задаётся только сама пара опор. */
    if (p.nextId === undefined) p.nextId = '';
    if (p.prevId === undefined) p.prevId = '';
    if (p.nextRef === undefined) p.nextRef = '';
    if (p.prevRef === undefined) p.prevRef = '';
    /* Пролёт определяется только координатами. Прежняя метка «введён вручную»
       силы больше не имеет: снимаем её, чтобы пересчёт прошёл по всем опорам. */
    if (p.spanSrc === 'manual') p.spanSrc = '';
  });
  relinkNeighbours(o);
  fixMeasLines(o);
  syncObjectLength(o);
  o.meas.forEach(function(m){
    if (!m.proto) m.proto = measProto(m.kindId);
    /* Отклонение стойки от вертикали раньше вводилось в миллиметрах, теперь —
       в градусах. Пересчитываем ранее введённые записи, иначе они потеряли бы
       значение: deg = arctg(dev / (H·1000)). */
    if (m.kindId === 'vert' && m.vals && m.vals.deg === undefined){
      var dv = parseFloat(String(m.vals.dev).replace(',', '.'));
      var hh = parseFloat(String(m.vals.h).replace(',', '.'));
      if (dv > 0 && hh > 0)
        m.vals.deg = Math.round(Math.atan(dv/(hh*1000)) * 180/Math.PI * 100) / 100;
    }
  });
  o.cables.forEach(function(c){ if (c.kv === undefined) c.kv = ''; if (c.tens === undefined) c.tens = ''; });
  o.wires.forEach(function(w){
    if (w.tens === undefined) w.tens = '';
    if (w.kv === undefined) w.kv = '';
  });
  o.skips.forEach(function(sk){
    if (!Array.isArray(sk.photoIds)) sk.photoIds = [];
    if (sk.imgs === undefined) sk.imgs = sk.photoIds.length;
  });
  o.acts = (o.acts || []).filter(function(a){ return a && (a.key || a.manual); });
  o.v = VERSION;
  return o;
}

/* Сведения о последней попытке загрузить шаблон — нужны для диагностики:
   разные хостинги отдают .xlsx по-разному, и молчаливое зависание запроса
   выглядело как «отчёт не формируется». */
var _tplInfo = { tried:false, ok:false, status:0, type:'', bytes:0, zip:false, error:'' };
function templateInfo(){ return _tplInfo; }

/* Структурная проверка книги ДО разбора.
   Некоторые хостинги отдают .xlsx как текст и портят его перекодировкой:
   файл по-прежнему начинается с «PK» и даже сохраняет сигнатуру конца архива,
   но смещения внутри уже не соответствуют содержимому. На таком файле XLSX.read
   уходит в бесконечный цикл и намертво блокирует вкладку — сторожевой таймер
   при этом бесполезен, поток занят. Поэтому проверяем целостность сами. */
function zipIntegrity(buf){
  var b = new Uint8Array(buf), n = b.length;
  if (n < 1000) return { ok:false, why:'файл слишком мал (' + n + ' байт)' };
  if (!(b[0] === 0x50 && b[1] === 0x4B && b[2] === 0x03 && b[3] === 0x04))
    return { ok:false, why:'файл не начинается заголовком ZIP' };

  /* ищем сигнатуру конца центрального каталога в последних 64 КБ */
  var from = Math.max(0, n - 65557), eocd = -1;
  for (var i = n - 22; i >= from; i--){
    if (b[i] === 0x50 && b[i+1] === 0x4B && b[i+2] === 0x05 && b[i+3] === 0x06){ eocd = i; break; }
  }
  if (eocd < 0) return { ok:false, why:'не найден конец ZIP-архива' };

  var u32 = function(o){ return b[o] | (b[o+1] << 8) | (b[o+2] << 16) | (b[o+3] << 24); };
  var u16 = function(o){ return b[o] | (b[o+1] << 8); };
  var entries = u16(eocd + 10), cdSize = u32(eocd + 12) >>> 0, cdOff = u32(eocd + 16) >>> 0;

  if (!entries) return { ok:false, why:'в архиве нет записей' };
  if (cdOff + cdSize > n)
    return { ok:false, why:'каталог архива выходит за границы файла — файл повреждён при передаче' };
  if (!(b[cdOff] === 0x50 && b[cdOff+1] === 0x4B && b[cdOff+2] === 0x01 && b[cdOff+3] === 0x02))
    return { ok:false, why:'смещения внутри архива не совпадают с содержимым — файл повреждён при передаче' +
                           ' (вероятно, отдан как текст и перекодирован)' };
  return { ok:true, entries:entries };
}

function loadTemplate(opts){
  opts = opts || {};
  if (_tplBuf) return Promise.resolve(_tplBuf);
  if (typeof fetch !== 'function')
    return Promise.reject(new Error('Браузер не поддерживает fetch'));

  var ms = opts.timeout || 8000;
  _tplInfo = { tried:true, ok:false, status:0, type:'', bytes:0, zip:false, error:'' };

  return new Promise(function(resolve, reject){
    var done = false;
    /* жёсткий предел ожидания: без него зависший запрос останавливал всю цепочку */
    var timer = setTimeout(function(){
      if (done) return;
      done = true;
      _tplInfo.error = 'превышено время ожидания ' + ms + ' мс';
      reject(new Error(_tplInfo.error));
    }, ms);

    fetch(TPL_URL, { cache:'no-cache' })
      .then(function(r){
        _tplInfo.status = r.status;
        _tplInfo.type = r.headers && r.headers.get ? (r.headers.get('content-type') || '') : '';
        if (!r.ok) throw new Error('HTTP ' + r.status);
        return r.arrayBuffer();
      })
      .then(function(b){
        _tplInfo.bytes = b.byteLength;
        /* xlsx — это zip: первые байты должны быть PK. Иначе хостинг отдал
           HTML-заглушку, указатель LFS или испортил файл перекодировкой. */
        var chk = zipIntegrity(b);
        _tplInfo.zip = chk.ok;
        if (!chk.ok)
          throw new Error(chk.why + ' (получено ' + b.byteLength +
                          ' байт, тип «' + (_tplInfo.type || 'не указан') + '»)');
        _tplInfo.ok = true;
        _tplBuf = b;
        if (done) return;
        done = true; clearTimeout(timer); resolve(b);
      })
      .catch(function(e){
        if (!_tplInfo.error) _tplInfo.error = e && e.message ? e.message : String(e);
        if (done) return;
        done = true; clearTimeout(timer); reject(e);
      });
  });
}

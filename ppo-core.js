/* ============================ ЛИНИЯ ИЗМЕРЕНИЯ — ПРОИЗВОДНАЯ ОТ ОПОРЫ
   Измерение выполняется на конкретной ОПОРЕ; линия у него не самостоятельная
   величина, а свойство этой опоры. Пока её вводили руками, в поле попадал
   комментарий («ВЛ-10 ТМ-6 наклон опоры»), и строка протокола отрывалась от
   объекта. Подставляем линию от опоры, к которой измерение привязано.     */
function fixMeasLines(d){
  if (!d || !d.meas || !d.poles) return 0;
  /* Номер опоры не уникален: каждая линия нумеруется с 1. Раньше линия бралась
     у ПЕРВОЙ опоры с таким номером, и при каждой загрузке измерения опор № 1, 2,
     3 второй линии переписывались на первую. Теперь: если на линии измерения
     опора с этим номером есть — линия верна и не трогается; подставляем линию,
     только когда опора с таким номером одна и выбор однозначен. */
  var byNum = {}, n = 0;
  d.poles.forEach(function(p){
    var k = String(p.num || '').trim().toLowerCase();
    if (!k) return;
    var l = String(p.line || '');
    if (!byNum[k]) byNum[k] = [];
    if (byNum[k].indexOf(l) < 0) byNum[k].push(l);
  });
  d.meas.forEach(function(m){
    var k = String(m.pole || '').trim().toLowerCase();
    var lines = k ? byNum[k] : null;
    if (!lines) return;
    var cur = String(m.line || '');
    if (lines.indexOf(cur) >= 0) return;
    if (lines.length === 1){ m.line = lines[0]; n++; }
  });
  return n;
}

/* ============================== НОМЕР ОПОРЫ ИЗ ЕЁ НАИМЕНОВАНИЯ
   Строгий разбор PPOKMZ.parseLabel рассчитан на полевой формат подписи
   «номер:тип:линия» и на всём остальном возвращает пустой номер. Человек же
   переименовывает метку на карте свободно: «Опора 93», «оп. № 95», «97а».
   Строгий разбор такие подписи не понимал, номер не менялся, и правка
   наименования до раздела «Осмотр» не доходила — при том, что координаты и
   признаки уходили. Здесь разбор мягкий: сначала полевой формат, затем
   отбрасывание служебных слов, затем — наименование как есть.            */
function poleNumFromName(name){
  var t = String(name === undefined || name === null ? '' : name).trim();
  if (!t) return '';
  /* 1. полевой формат подписи — им же пользуется импорт KMZ */
  if (typeof PPOKMZ !== 'undefined' && PPOKMZ.parseLabel){
    try {
      var r = PPOKMZ.parseLabel(t, '');
      if (r && r.num && String(r.num).trim()) return String(r.num).trim();
    } catch (e) { /* разбор не удался — идём дальше */ }
  }
  /* 2. отбрасываем служебные слова и знак номера */
  var c = t.replace(/^[\s.,;:\-–—]+/, '');
  var prev = null;
  while (c !== prev){
    prev = c;
    c = c.replace(/^(опор[аыу]?|оп\.?|стойк[аиу]?|ст\.?|точк[аиу]?|тчк\.?|point|pt\.?)\b[\s.,;:\-–—]*/i, '')
         .replace(/^(№|N[o°]?|#)[\s.,;:\-–—]*/i, '')
         .replace(/^[\s.,;:\-–—]+/, '');
  }
  /* 3. первый фрагмент, начинающийся с цифры: «93», «92/1а», «1-11а», «97а».
     Одиночная буква через пробел («12 б») относится к номеру и приклеивается;
     целое слово («45 ввод») — уже не литера опоры и остаётся снаружи. */
  var m = c.match(/\d+(?:[\/\-.][\dA-Za-zА-Яа-яЁё]+)*[A-Za-zА-Яа-яЁё]*(?:\s[A-Za-zА-Яа-яЁё](?![A-Za-zА-Яа-яЁё]))?/);
  if (m && m[0]) return m[0].replace(/\s+/g, '');
  /* 4. цифр нет вовсе — наименование само служит обозначением опоры */
  return c.trim() || t;
}

/* Все линии, встречающиеся в проекте: описанные на вкладке «Линии» и те,
   что проставлены у опор. Используется в поле «Наименование объекта»:
   объект обследования почти всегда складывается из нескольких фидеров, и
   перечислять их руками — источник расхождения между разделами отчёта. */
function projectLines(){
  var d = load(), seen = {}, out = [];
  function put(v){
    var t = String(v === undefined || v === null ? '' : v).trim();
    if (!t || seen[t.toLowerCase()]) return;
    seen[t.toLowerCase()] = 1; out.push(t);
  }
  (d.lines || []).forEach(function(l){ put(l.disp || l.line); });
  (d.poles || []).forEach(function(p){ put(p.line); });
  out.sort(function(a, b){ return cmpPoleNum(a, b); });
  return out;
}

/* ================= УДАЛЕНИЕ ОПОРЫ ПО МЕТКЕ КАРТЫ
   Метка на карте и опора в осмотре — один объект, показанный с двух сторон.
   Раньше удаление метки убирало её только с карты, а опора оставалась в
   осмотре и продолжала участвовать в цепи пролётов и в отчёте.
   Ищем ту же цель и тем же порядком, что и перенос: идентификатор → пара
   «линия + номер» → координаты. */
function deletePoleForMark(m){
  var d = load();
  var src = markToPole(m || {});
  var tgt = null;
  if (src.poleId) d.poles.forEach(function(p){ if (!tgt && p.id === src.poleId) tgt = p; });
  if (!tgt && src.num) d.poles.forEach(function(p){
    if (!tgt && keyOf(p.line, p.num) === keyOf(src.line, src.num)) tgt = p; });
  if (!tgt) d.poles.forEach(function(p){ if (!tgt && sameSpot(p, src)) tgt = p; });
  if (!tgt) return { removed:0 };

  var num = String(tgt.num || ''), line = String(tgt.line || ''), id = tgt.id;
  d.poles = d.poles.filter(function(p){ return p.id !== id; });
  /* ссылки соседей на удалённую опору снимаем: иначе цепь указывала бы в
     пустоту, а пролёт считался бы до несуществующей точки */
  var relinked = 0;
  d.poles.forEach(function(p){
    ['next', 'prev'].forEach(function(w){
      if (p[w + 'Id'] === id){ p[w + 'Id'] = ''; p[w + 'Ref'] = ''; relinked++; }
    });
  });
  /* измерения и фотографии, привязанные к опоре, остаются: удаление опоры не
     означает, что измерения не выполнялись. Но об осиротевших сообщаем. */
  var meas = (d.meas || []).filter(function(x){
    return String(x.pole || '').trim() === num && String(x.line || '').trim() === line; }).length;
  replaceAll(d);
  recalcSpans({ force:true });
  return { removed:1, num:num, line:line, relinked:relinked, meas:meas };
}

/* ================= ПРИЗНАКИ ЦЕПИ, ЗАДАВАЕМЫЕ С КАРТЫ
   Конец участка и ручная привязка соседей правятся и в карточке опоры, и в
   карточке метки. Значения одни и те же, поэтому запись идёт через общую
   точку, а не двумя разными путями. */
function setPoleLinks(poleId, opts){
  var d = load(), tgt = null;
  d.poles.forEach(function(p){ if (p.id === poleId) tgt = p; });
  if (!tgt) return null;
  opts = opts || {};
  if (opts.endPole !== undefined) tgt.endPole = opts.endPole ? 1 : 0;
  ['next', 'prev'].forEach(function(w){
    if (opts[w + 'Id'] === undefined) return;
    tgt[w + 'Id'] = String(opts[w + 'Id'] || '');
    if (!tgt[w + 'Id']) tgt[w + 'Ref'] = '';
  });
  if (tgt.endPole){ tgt.span = ''; tgt.spanSrc = ''; }
  replaceAll(d);
  recalcSpans({ force:true });
  return tgt;
}

/* Характеристики опоры, правимые из карточки метки на карте.
   Полевой обход нередко даёт неверную линию или класс напряжения — их нужно
   уметь поправить там же, на карте, не уходя в «Осмотр». Пишем через общую
   точку и тем же набором правил, что и карточка опоры. */
var POLE_EDITABLE = ['line','kv','mark','poleType','hangs','mest','angle',
                     'prevOwner','prevH','note','defText'];
function updatePoleFields(poleId, obj){
  var d = load(), tgt = null;
  d.poles.forEach(function(p){ if (p.id === poleId) tgt = p; });
  if (!tgt || !obj) return null;
  var changed = 0;
  POLE_EDITABLE.forEach(function(k){
    if (obj[k] === undefined) return;
    var v = obj[k];
    /* класс напряжения пишем в том виде, в каком он задан в справочнике:
       «0.4» и «0,4» — один класс, но фильтры сравнивают строки */
    if (k === 'kv'){
      var t = String(v === undefined || v === null ? '' : v).trim().replace('.', ',');
      var hit = LISTS.kv.filter(function(x){ return x === t; })[0];
      v = hit || t;
    }
    v = (v === null) ? '' : v;
    if (String(tgt[k] === undefined ? '' : tgt[k]) === String(v)) return;
    tgt[k] = v; changed++;
  });
  if (obj.defect !== undefined){
    var c = normCat(obj.defect);
    if (tgt.defect !== c){ tgt.defect = c; changed++; }
  }
  if (!changed) return tgt;
  replaceAll(d);
  /* линия могла смениться — цепь пролётов перестраивается */
  recalcSpans({ force:true });
  return tgt;
}

/* ============================ КЭШ ЦЕПИ ПРОЛЁТОВ
   Построение цепи — самая дорогая операция ядра, а за одно действие на карте
   она запрашивалась пять-шесть раз подряд: карточкой метки, обоими полями
   соседей, перекраской. Данные между этими вызовами не меняются, поэтому
   результат держим до ближайшей записи объекта. Ревизию поднимает save(). */
var _chainCache = null;
function poleChain(){
  var d = load();
  if (_chainCache && _chainCache.rev === _rev) return _chainCache;
  var byItem, gaps = {};
  try { byItem = chainSpans(d.poles).byItem; }
  catch (e) { return { rev:_rev, d:d, byItem:new Map(), gaps:{} }; }
  d.poles.forEach(function(p){ gaps[p.id] = poleLinkGap(p, byItem.get(p) || null); });
  _chainCache = { rev:_rev, d:d, byItem:byItem, gaps:gaps };
  return _chainCache;
}
/* запись цепи по конкретной опоре — без повторного построения */
function chainRecOf(pole){
  if (!pole) return null;
  var c = poleChain();
  var src = c.d.poles.filter(function(x){ return x.id === pole.id; })[0];
  return src ? (c.byItem.get(src) || null) : null;
}

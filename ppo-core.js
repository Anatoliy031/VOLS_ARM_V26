/* доля тяжения, передающаяся на опору как неуравновешенная (доли единицы) */
function tensionShare(sch, angleDeg){
  var t = String(sch||'');
  if (/концев/.test(t)) return 1.0;                       // одностороннее тяжение
  if (/ответвит/.test(t)) return 1.0;                     // тяжение ответвления
  if (/углов/.test(t)){
    var a = parseFloat(angleDeg);
    if (!(a > 0)) return 1.0;                             // угол не задан — в запас
    return 2 * Math.sin(a * Math.PI / 360);               // 2*sin(α/2)
  }
  if (/анкер/.test(t)) return 0.3;                        // монтажная неуравновешенность
  return 0;
}

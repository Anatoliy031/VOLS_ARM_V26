/* Данные осмотра — первичны. Всё остальное, что пишут другие разделы в то же
   локальное хранилище (кэш карты и т. п.), при нехватке места приносится в
   жертву: раньше переполнение квоты роняло запись молча, объект осмотра не
   сохранялся, и отчёт потом сообщал «в осмотре нет данных». */
var SACRIFICIAL_KEYS = ['ppo_map_state_v1'];

function save(){
  var d = load();
  d.saved = new Date().toISOString();
  _rev++;                       /* данные изменились — кэш цепи недействителен */
  var payload = JSON.stringify(d);

  /* отметка записи: по ней другие вкладки понимают, что объект изменился */
  _stamp = newStamp();
  try { localStorage.setItem(STORE_KEY + '_stamp', _stamp); } catch (eS) {}

  try { localStorage.setItem(STORE_KEY, payload); }
  catch (e) {
    var freed = [];
    /* освобождаем место за счёт вспомогательных кэшей и пробуем ещё раз */
    for (var i = 0; i < SACRIFICIAL_KEYS.length; i++){
      try {
        if (localStorage.getItem(SACRIFICIAL_KEYS[i]) !== null){
          localStorage.removeItem(SACRIFICIAL_KEYS[i]);
          freed.push(SACRIFICIAL_KEYS[i]);
        }
      } catch (e2) {}
    }
    var second = false;
    if (freed.length){
      try { localStorage.setItem(STORE_KEY, payload); second = true; }
      catch (e3) { second = false; }
    }
    if (!second){
      console.warn('Не удалось сохранить данные осмотра:', e);
      try {
        document.dispatchEvent(new CustomEvent('ppo:savefail', {
          detail:{ reason:'quota', bytes: payload.length, freed: freed }
        }));
      } catch (e4) {}
      return false;
    }
    try {
      document.dispatchEvent(new CustomEvent('ppo:cachedropped', { detail:{ keys: freed } }));
    } catch (e5) {}
  }
  document.dispatchEvent(new CustomEvent('ppo:saved'));
  return true;
}

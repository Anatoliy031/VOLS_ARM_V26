function isWorkday(d){ var w = d.getDay(); return w !== 0 && w !== 6; }
/* Течение срока начинается со следующего рабочего дня после события
   (п. 6.2.1), поэтому отсчёт всегда идёт от дня, следующего за базовым. */
function addWorkdays(start, k){
  if (!start) return null;
  var d = new Date(start.getTime()), left = k;
  while (left > 0){ d.setDate(d.getDate() + 1); if (isWorkday(d)) left--; }
  return d;
}
function workdaysBetween(a, b){
  if (!a || !b) return null;
  var sign = b < a ? -1 : 1, from = sign > 0 ? a : b, to = sign > 0 ? b : a;
  var d = new Date(from.getTime()), n = 0;
  while (d < to){ d.setDate(d.getDate() + 1); if (isWorkday(d)) n++; }
  return n * sign;
}
function parseRuDate(v){
  if (!v) return null;
  if (v instanceof Date) return isNaN(v) ? null : v;
  var s = String(v).trim();
  var m = s.match(/^(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{4})$/);
  if (m) return new Date(+m[3], +m[2] - 1, +m[1]);
  m = s.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (m) return new Date(+m[1], +m[2] - 1, +m[3]);
  var d = new Date(s);
  return isNaN(d) ? null : d;
}

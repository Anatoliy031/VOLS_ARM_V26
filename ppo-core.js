/* Переприкрепление уже сохранённых снимков к другой опоре.
   Нужно, когда метка KMZ превращается в опору: файлы лежат в базе с прежней
   (пустой) привязкой, и без обновления они не попадали бы в фотоприложение
   отчёта, хотя в карточке опоры видны. */
function photoRelink(ids, pole, line){
  var list = (ids || []).slice();
  if (!list.length) return Promise.resolve(0);
  var n = 0;
  return list.reduce(function(ch, id){
    return ch.then(function(){
      return photoGet(id).then(function(rec){
        if (!rec) return;
        rec.pole = String(pole || '');
        rec.line = String(line || '');
        return photoPut(rec).then(function(){ n++; });
      }).catch(function(){});
    });
  }, Promise.resolve()).then(function(){ return n; });
}


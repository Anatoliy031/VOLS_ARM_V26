function measById(id){
  for (var i=0;i<MEAS.length;i++) if (MEAS[i].id === id) return MEAS[i];
  return null;
}
function measByName(n){
  for (var i=0;i<MEAS.length;i++) if (MEAS[i].name === n) return MEAS[i];
  return null;
}
/* единая точка расчёта: возвращает {value, unit, norm, verdict} или null */
function evalMeas(id, vals, ctx){
  var m = measById(id); if (!m) return null;
  var res = m.compute(vals, ctx||{});
  if (!res) return null;
  var v = m.verdict(res, ctx||{});
  if (m.g2) v = (v === 'соответствует') ? 'достаточно' : 'недостаточно';
  return {
    id:m.id, name:m.name, place:m.place, unit:m.unit, proto:measProto(m.id),
    value:res.value, norm:m.norm(res, ctx||{}), verdict:v, res:res,
    /* развёрнутая запись измерения, если вид измерения её даёт: например,
       отклонение от вертикали показывает угол, миллиметры и вид 1/N разом */
    detail: (typeof m.detail === 'function') ? m.detail(res, ctx||{}) : ''
  };
}
/* единый признак «есть несоответствие» для мероприятий и аудита */
function isBadVerdict(v){
  var t = String(v||'').trim().toLowerCase();
  return t.indexOf('не соответствует') === 0 || t.indexOf('недостаточно') === 0;
}


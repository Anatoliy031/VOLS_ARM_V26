/* =====================================================================
   Сквозная синхронизация «Карта» ↔ «Осмотр → Опоры».
   Единая реализация: обе страницы правят один и тот же набор опор.
   Сопоставление — по паре «линия + номер опоры», при их отсутствии —
   по координатам с допуском ~1,5 м. Ручные правки в «Осмотре» (марка,
   пролёт, класс, примечание) при обновлении с карты не затираются.
   ===================================================================== */
var GEO_TOL = 0.000015;   // ≈1,5 м по широте

function sameSpot(a, b){
  var la = parseFloat(a.lat), lo = parseFloat(a.lon),
      lb = parseFloat(b.lat), ob = parseFloat(b.lon);
  if (!(la && lo && lb && ob)) return false;
  return Math.abs(la-lb) < GEO_TOL && Math.abs(lo-ob) < GEO_TOL * 2;
}
function keyOf(line, num){
  return String(line||'').trim().toLowerCase() + '|' + String(num||'').trim().toLowerCase();
}
/* марка опоры по «типу», выбранному на карте, в пределах класса напряжения */
function markByType(kv, poleType){
  var t = String(poleType||'').trim().toLowerCase();
  if (!t) return '';
  var list = kv ? polesByKv(kv) : POLES;
  var hit = null;
  list.forEach(function(r){
    if (hit) return;
    var rt = String(r.type||'').toLowerCase();
    if (rt.indexOf(t) === 0 || t.indexOf(rt.split(' (')[0]) === 0) hit = r;
  });
  if (!hit) list.forEach(function(r){
    if (hit) return;
    if (String(r.type||'').toLowerCase().indexOf(t.split(' ')[0]) >= 0) hit = r;
  });
  return hit ? hit.mark : '';
}
/* Метка карты → поля опоры. Возвращает объект только с теми полями,
   которые карта действительно ведёт: остальное принадлежит «Осмотру». */
function markToPole(m){
  return {
    /* Идентификатор опоры, за которой закреплена метка. Раньше он терялся,
       и при переименовании опоры на карте сопоставление шло только по паре
       «линия + номер»: новый номер не совпадал ни с чем, опора в осмотре
       оставалась под старым номером, хотя координаты и признаки обновлялись.
       С идентификатором связь метки и опоры переименование переживает. */
    poleId: String(m.poleId || '').trim(),
    line: String(m.line || m.folder || '').trim(),
    num:  String(m.pole || '').trim(),
    defect: normCat(m.defect),
    lat: (m.lat !== undefined && m.lat !== '') ? String(m.lat) : '',
    lon: (m.lon !== undefined && m.lon !== '') ? String(m.lon) : '',
    poleType: String(m.poleType || '').trim(),
    name: String(m.name || '').trim(),
    /* Поля, разобранные из подписи метки тем же модулем, что и при импорте
       KMZ. Раньше карта их не передавала, и опора приходила в осмотр без
       марки, класса напряжения, примечания и с папкой KML вместо линии. */
    kv:    String(m.kv || '').trim(),
    mark:  String(m.mark || '').trim(),
    fieldMark: String(m.fieldMark || '').trim(),
    note:  String(m.note || '').trim(),
    /* пролёт храним числом, как это делает пересчёт по координатам: иначе
       «50» и 50 считались бы разными значениями и книга получала бы то текст,
       то число в одной и той же графе */
    span:  (m.span === undefined || m.span === null || m.span === '') ? ''
           : (isFinite(m.span) ? Number(m.span) : String(m.span)),
    combined: !!m.combined,
    when:  String(m.when || '')
  };
}
/* Примечание опоры: складываем наблюдения, не дублируя уже записанное. */
function mergeNote(old, add){
  var have = String(old || '');
  String(add || '').split(';').forEach(function(part){
    var t = part.trim();
    if (t && have.indexOf(t) < 0) have = have ? have + '; ' + t : t;
  });
  return have;
}
